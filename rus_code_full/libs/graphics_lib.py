# === Рисование звёзд ===
def _звезда(x, y, внешний_радиус, внутренний_радиус=None, лучей=5, цвет=None, заполнение=None):
    if внутренний_радиус is None:
        внутренний_радиус = внешний_радиус / 2
    
    цвет = цвет or _состояние['текущий_цвет']
    заполнение = заполнение or 'none'
    
    точки = []
    for i in range(лучей * 2):
        угол = math.radians(i * 180 / лучей - 90)
        r = внешний_радиус if i % 2 == 0 else внутренний_радиус
        px = x + r * math.cos(угол)
        py = y + r * math.sin(угол)
        точки.append((px, py))
    
    элемент = {'тип': 'звезда', 'центр': (x, y), 'точки': точки, 'цвет': цвет, 'заполнение': заполнение}
    _состояние['элементы'].append(элемент)
    return элемент

функции['звезда'] = _звезда
функции['нарисовать_звезду'] = _звезда

