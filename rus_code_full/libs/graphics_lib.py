# === Трансформации ===
def _переместить(элемент, dx, dy):
    if 'x' in элемент:
        элемент['x'] += dx
    if 'y' in элемент:
        элемент['y'] += dy
    if 'x1' in элемент:
        элемент['x1'] += dx
        элемент['x2'] += dx
    if 'y1' in элемент:
        элемент['y1'] += dy
        элемент['y2'] += dy
    if 'точки' in элемент:
        элемент['точки'] = [(x+dx, y+dy) for x, y in элемент['точки']]
    return элемент

функции['переместить'] = _переместить

def _масштабировать(элемент, factor):
    if 'радиус' in элемент:
        элемент['радиус'] *= factor
    if 'ширина' in элемент:
        элемент['ширина'] *= factor
    if 'высота' in элемент:
        элемент['высота'] *= factor
    if 'rx' in элемент:
        элемент['rx'] *= factor
        элемент['ry'] *= factor
    return элемент

функции['масштабировать'] = _масштабировать

def _повернуть(элемент, угол, cx=0, cy=0):
    # Упрощённая реализация
    рад = math.radians(угол)
    cos_a = math.cos(рад)
    sin_a = math.sin(рад)
    
    if 'точки' in элемент:
        новые_точки = []
        for x, y in элемент['точки']:
            nx = cx + (x - cx) * cos_a - (y - cy) * sin_a
            ny = cy + (x - cx) * sin_a + (y - cy) * cos_a
            новые_точки.append((nx, ny))
        элемент['точки'] = новые_точки
    
    return элемент

функции['повернуть'] = _повернуть

# === Сохранение в SVG ===
def _в_svg():
    svg = f'<svg width="{_состояние["ширина"]}" height="{_состояние["высота"]}" xmlns="http://www.w3.org/2000/svg">\n'
    
    for elem in _состояние['элементы']:
        тип = elem.get('тип')
        
        if тип == 'точка':
            svg += f'  <circle cx="{elem["x"]}" cy="{elem["y"]}" r="2" fill="{elem["цвет"]}"/>\n'
        
        elif тип == 'линия':
            svg += f'  <line x1="{elem["x1"]}" y1="{elem["y1"]}" x2="{elem["x2"]}" y2="{elem["y2"]}" stroke="{elem["цвет"]}" stroke-width="{elem["толщина"]}"/>\n'
        
        elif тип == 'круг':
            fill = elem.get('заполнение', 'none')
            svg += f'  <circle cx="{elem["x"]}" cy="{elem["y"]}" r="{elem["радиус"]}" stroke="{elem["цвет"]}" fill="{fill}"/>\n'
        
        elif тип == 'эллипс':
            fill = elem.get('заполнение', 'none')
            svg += f'  <ellipse cx="{elem["x"]}" cy="{elem["y"]}" rx="{elem["rx"]}" ry="{elem["ry"]}" stroke="{elem["цвет"]}" fill="{fill}"/>\n'
        
        elif тип == 'прямоугольник':
            fill = elem.get('заполнение', 'none')
            svg += f'  <rect x="{elem["x"]}" y="{elem["y"]}" width="{elem["ширина"]}" height="{elem["высота"]}" stroke="{elem["цвет"]}" fill="{fill}"/>\n'
        
        elif тип == 'треугольник' or тип == 'многоугольник':
            points = ' '.join(f'{x},{y}' for x, y in elem['точки'])
            fill = elem.get('заполнение', 'none')
            svg += f'  <polygon points="{points}" stroke="{elem["цвет"]}" fill="{fill}"/>\n'
        
        elif тип == 'текст':
            svg += f'  <text x="{elem["x"]}" y="{elem["y"]}" fill="{elem["цвет"]}" font-family="{elem["шрифт"]}" font-size="{elem["размер"]}">{elem["текст"]}</text>\n'
    
    svg += '</svg>'
    return svg

функции['в_svg'] = _в_svg

def _сохранить_svg(путь):
    svg = _в_svg()
    with open(путь, 'w', encoding='utf-8') as f:
        f.write(svg)
    return путь

функции['сохранить_svg'] = _сохранить_svg

