# === RGB цвета ===
def _rgb(r, g, b):
    r, g, b = int(r), int(g), int(b)
    r = max(0, min(255, r))
    g = max(0, min(255, g))
    b = max(0, min(255, b))
    return f'#{r:02x}{g:02x}{b:02x}'

функции['rgb'] = _rgb

