"""
Библиотека математики для РусКод
Расширенные математические функции и операции
"""

import math
from typing import List, Union

class Математика:
    """Расширенная математическая библиотека"""
    
    @staticmethod
    def факториал(n: int) -> int:
        """Вычисление факториала числа"""
        if n < 0:
            return 0
        if n == 0 or n == 1:
            return 1
        результат = 1
        for i in range(2, n + 1):
            результат *= i
        return результат
    
    @staticmethod
    def нод(a: int, b: int) -> int:
        """Наибольший общий делитель"""
        while b:
            a, b = b, a % b
        return abs(a)
    
    @staticmethod
    def нок(a: int, b: int) -> int:
        """Наименьшее общее кратное"""
        return abs(a * b) // Математика.нод(a, b) if a and b else 0
    
    @staticmethod
    def простое_число(n: int) -> bool:
        """Проверка числа на простоту"""
        if n < 2:
            return False
        if n == 2:
            return True
        if n % 2 == 0:
            return False
        for i in range(3, int(math.sqrt(n)) + 1, 2):
            if n % i == 0:
                return False
        return True
    
    @staticmethod
    def простые_числа(до: int) -> List[int]:
        """Список простых чисел до указанного"""
        простые = []
        for n in range(2, до + 1):
            if Математика.простое_число(n):
                простые.append(n)
        return простые
    
    @staticmethod
    def числа_фибоначчи(n: int) -> List[int]:
        """Первые n чисел Фибоначчи"""
        if n <= 0:
            return []
        if n == 1:
            return [0]
        числа = [0, 1]
        for i in range(2, n):
            числа.append(числа[i-1] + числа[i-2])
        return числа
    
    @staticmethod
    def число_фибоначчи(n: int) -> int:
        """N-е число Фибоначчи"""
        if n <= 0:
            return 0
        if n == 1:
            return 0
        if n == 2:
            return 1
        a, b = 0, 1
        for _ in range(3, n + 1):
            a, b = b, a + b
        return b
    
    @staticmethod
    def перестановки(n: int, k: int = None) -> int:
        """Число перестановок из n по k"""
        if k is None:
            k = n
        if k > n:
            return 0
        return Математика.факториал(n) // Математика.факториал(n - k)
    
    @staticmethod
    def сочетания(n: int, k: int) -> int:
        """Число сочетаний из n по k"""
        if k > n or k < 0:
            return 0
        return Математика.факториал(n) // (Математика.факториал(k) * Математика.факториал(n - k))
    
    @staticmethod
    def проценты(сумма: float, процент: float) -> float:
        """Вычисление процента от суммы"""
        return сумма * процент / 100
    
    @staticmethod
    def изменение_процентов(старое: float, новое: float) -> float:
        """Процент изменения между значениями"""
        if старое == 0:
            return 0
        return ((новое - старое) / старое) * 100
    
    @staticmethod
    def среднее_арифметическое(*числа) -> float:
        """Среднее арифметическое"""
        return sum(числа) / len(числа) if числа else 0
    
    @staticmethod
    def среднее_геометрическое(*числа) -> float:
        """Среднее геометрическое"""
        if not числа:
            return 0
        произведение = 1
        for x in числа:
            произведение *= x
        return произведение ** (1 / len(числа))
    
    @staticmethod
    def дисперсия(данные: List[float]) -> float:
        """Дисперсия набора данных"""
        if not данные:
            return 0
        среднее = sum(данные) / len(данные)
        return sum((x - среднее) ** 2 for x in данные) / len(данные)
    
    @staticmethod
    def стандартное_отклонение(данные: List[float]) -> float:
        """Стандартное отклонение"""
        return math.sqrt(Математика.дисперсия(данные))
    
    @staticmethod
    def медиана(данные: List[float]) -> float:
        """Медиана набора данных"""
        if not данные:
            return 0
        отсортированные = sorted(данные)
        n = len(отсортированные)
        середина = n // 2
        if n % 2 == 0:
            return (отсортированные[сердина - 1] + отсортированные[сердина]) / 2
        return отсортированные[сердина]
    
    @staticmethod
    def мода(данные: List[float]) -> List[float]:
        """Мода (наиболее часто встречающиеся значения)"""
        if not данные:
            return []
        from collections import Counter
        подсчет = Counter(данные)
        макс_частота = max(подсчет.values())
        return [x for x, частота in подсчет.items() if частота == макс_частота]
    
    @staticmethod
    def нод_нескольких(*числа) -> int:
        """НОД нескольких чисел"""
        if not числа:
            return 0
        результат = числа[0]
        for x in числа[1:]:
            результат = Математика.нод(результат, x)
        return результат
    
    @staticmethod
    def нок_нескольких(*числа) -> int:
        """НОК нескольких чисел"""
        if not числа:
            return 0
        результат = числа[0]
        for x in числа[1:]:
            результат = Математика.нок(результат, x)
        return результат
    
    @staticmethod
    def разложить_на_множители(n: int) -> List[int]:
        """Разложение числа на простые множители"""
        множители = []
        d = 2
        while d * d <= n:
            while n % d == 0:
                множители.append(d)
                n //= d
            d += 1
        if n > 1:
            множители.append(n)
        return множители
    
    @staticmethod
    def все_делители(n: int) -> List[int]:
        """Все делители числа"""
        делители = []
        for i in range(1, int(math.sqrt(n)) + 1):
            if n % i == 0:
                делители.append(i)
                if i != n // i:
                    делители.append(n // i)
        return sorted(делители)
    
    @staticmethod
    def совершенное_число(n: int) -> bool:
        """Проверка числа на совершенность"""
        if n < 2:
            return False
        сумма_делителей = sum(Математика.все_делители(n)[:-1])
        return сумма_делителей == n
    
    @staticmethod
    def дружественные_числа(n: int) -> List[int]:
        """Поиск дружественных чисел для данного"""
        def сумма_собственных_делителей(x):
            return sum(Математика.все_делители(x)[:-1])
        
        сумма = сумма_собственных_делителей(n)
        if сумма != n and сумма_собственных_делителей(сумма) == n:
            return [n, сумма]
        return []
    
    @staticmethod
    def треугольное_число(n: int) -> int:
        """N-е треугольное число"""
        return n * (n + 1) // 2
    
    @staticmethod
    def квадратное_число(n: int) -> int:
        """N-е квадратное число"""
        return n * n
    
    @staticmethod
    def кубическое_число(n: int) -> int:
        """N-е кубическое число"""
        return n * n * n
    
    @staticmethod
    def проверить_треугольное(n: int) -> bool:
        """Является ли число треугольным"""
        k = int((math.sqrt(8 * n + 1) - 1) / 2)
        return Математика.треугольное_число(k) == n
    
    @staticmethod
    def проверить_квадратное(n: int) -> bool:
        """Является ли число квадратом целого"""
        корень = int(math.sqrt(n))
        return корень * корень == n
    
    @staticmethod
    def проверить_кубическое(n: int) -> bool:
        """Является ли число кубом целого"""
        корень = round(n ** (1/3))
        return корень * корень * корень == n
    
    @staticmethod
    def нод_расширенный(a: int, b: int) -> tuple:
        """Расширенный алгоритм Евклида (НОД, x, y) где ax + by = НОД"""
        if a == 0:
            return b, 0, 1
        нод, x1, y1 = Математика.нод_расширенный(b % a, a)
        x = y1 - (b // a) * x1
        y = x1
        return нод, x, y
    
    @staticmethod
    def модулярная_степень(base: int, exp: int, mod: int) -> int:
        """Вычисление (base^exp) mod mod"""
        результат = 1
        base = base % mod
        while exp > 0:
            if exp % 2 == 1:
                результат = (результат * base) % mod
            exp = exp >> 1
            base = (base * base) % mod
        return результат
    
    @staticmethod
    def обратный_элемент(a: int, m: int) -> int:
        """Мультипликативно обратный элемент a по модулю m"""
        нод, x, _ = Математика.нод_расширенный(a % m, m)
        if нод != 1:
            raise ValueError("Обратный элемент не существует")
        return (x % m + m) % m
    
    @staticmethod
    def китайская_теорема_об_остатках(остатки: List[int], модули: List[int]) -> int:
        """Решение системы сравнений с помощью Китайской теоремы об остатках"""
        произведение = 1
        for m in модули:
            произведение *= m
        
        результат = 0
        for остаток, модуль in zip(остатки, модули):
            p = произведение // модуль
            результат += остаток * Математика.обратный_элемент(p, модуль) * p
        
        return результат % произведение


