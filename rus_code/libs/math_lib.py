"""
Библиотека математических функций для РусКод
Все функции на русском языке без английских букв
"""

import math

class Математика:
    """Библиотека математических функций"""
    
    @staticmethod
    def сложить(а, б):
        """Сложение двух чисел"""
        return а + б
    
    @staticmethod
    def вычесть(а, б):
        """Вычитание второго числа из первого"""
        return а - б
    
    @staticmethod
    def перемножить(а, б):
        """Умножение двух чисел"""
        return а * б
    
    @staticmethod
    def поделить(а, б):
        """Деление первого числа на второе"""
        if б == 0:
            return "Ошибка: деление на ноль"
        return а / б
    
    @staticmethod
    def возвести_в_степень(основание, степень):
        """Возведение в степень"""
        return основание ** степень
    
    @staticmethod
    def квадратный_корень(число):
        """Квадратный корень"""
        if число < 0:
            return "Ошибка: корень из отрицательного числа"
        return math.sqrt(число)
    
    @staticmethod
    def кубический_корень(число):
        """Кубический корень"""
        return math.copysign(abs(число) ** (1/3), число)
    
    @staticmethod
    def модуль(число):
        """Модуль числа"""
        return abs(число)
    
    @staticmethod
    def округлить(число, знаков=0):
        """Округление числа"""
        return round(число, знаков)
    
    @staticmethod
    def потолок(число):
        """Округление до ближайшего большего целого"""
        return math.ceil(число)
    
    @staticmethod
    def пол(число):
        """Округление до ближайшего меньшего целого"""
        return math.floor(число)
    
    @staticmethod
    def максимум(*числа):
        """Максимальное значение из списка"""
        return max(числа)
    
    @staticmethod
    def минимум(*числа):
        """Минимальное значение из списка"""
        return min(числа)
    
    @staticmethod
    def среднее(*числа):
        """Среднее арифметическое"""
        return sum(числа) / len(числа)
    
    @staticmethod
    def сумма_списка(список):
        """Сумма элементов списка"""
        return sum(список)
    
    @staticmethod
    def произведение_списка(список):
        """Произведение элементов списка"""
        результат = 1
        for число in список:
            результат *= число
        return результат
    
    @staticmethod
    def факториал(число):
        """Факториал числа"""
        if число < 0:
            return "Ошибка: факториал отрицательного числа"
        if число == 0 or число == 1:
            return 1
        return math.factorial(число)
    
    @staticmethod
    def наибольший_общий_делитель(а, б):
        """Наибольший общий делитель (НОД)"""
        return math.gcd(а, б)
    
    @staticmethod
    def наименьшее_общее_кратное(а, б):
        """Наименьшее общее кратное (НОК)"""
        return abs(а * б) // math.gcd(а, б)
    
    @staticmethod
    def синус(угол):
        """Синус угла (в радианах)"""
        return math.sin(угол)
    
    @staticmethod
    def косинус(угол):
        """Косинус угла (в радианах)"""
        return math.cos(угол)
    
    @staticmethod
    def тангенс(угол):
        """Тангенс угла (в радианах)"""
        return math.tan(угол)
    
    @staticmethod
    def арксинус(значение):
        """Арксинус"""
        return math.asin(значение)
    
    @staticmethod
    def арккосинус(значение):
        """Арккосинус"""
        return math.acos(значение)
    
    @staticmethod
    def арктангенс(значение):
        """Арктангенс"""
        return math.atan(значение)
    
    @staticmethod
    def радианы_в_градусы(радианы):
        """Перевод радиан в градусы"""
        return math.degrees(радианы)
    
    @staticmethod
    def градусы_в_радианы(градусы):
        """Перевод градусов в радианы"""
        return math.radians(градусы)
    
    @staticmethod
    def число_пи():
        """Число Пи"""
        return math.pi
    
    @staticmethod
    def число_е():
        """Число Эйлера"""
        return math.e
    
    @staticmethod
    def логарифм(число, основание=math.e):
        """Логарифм числа по основанию"""
        if число <= 0 or основание <= 0:
            return "Ошибка: логарифм от неположительного числа"
        return math.log(число, основание)
    
    @staticmethod
    def натуральный_логарифм(число):
        """Натуральный логарифм"""
        return math.log(число)
    
    @staticmethod
    def десятичный_логарифм(число):
        """Десятичный логарифм"""
        return math.log10(число)
    
    @staticmethod
    def экспонента(число):
        """Экспонента (e^x)"""
        return math.exp(число)
    
    @staticmethod
    def случайное_число(мин=0, макс=100):
        """Случайное число в диапазоне"""
        import random
        return random.randint(мин, макс)
    
    @staticmethod
    def случайное_дробное(мин=0.0, макс=1.0):
        """Случайное дробное число"""
        import random
        return random.uniform(мин, макс)


