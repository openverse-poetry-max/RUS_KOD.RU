#!/usr/bin/env python3
# -*- кодировка: UTF-8 -*-

"""
Библиотека работы со строками для РусКод
Все функции на русском языке без английских букв
"""

class Строки:
    """Библиотека функций для работы со строками"""
    
    @staticmethod
    def длина(строка):
        """Длина строки"""
        return len(строка)
    
    @staticmethod
    def верхний_регистр(строка):
        """Перевод строки в верхний регистр"""
        return строка.upper()
    
    @staticmethod
    def нижний_регистр(строка):
        """Перевод строки в нижний регистр"""
        return строка.lower()
    
    @staticmethod
    def заглавные_буквы(строка):
        """Первая буква каждого слова заглавная"""
        return строка.title()
    
    @staticmethod
    def заменить(строка, старая, новая):
        """Замена подстроки в строке"""
        return строка.replace(старая, новая)
    
    @staticmethod
    def разделить(строка, разделитель=' '):
        """Разделение строки на части"""
        return строка.split(разделитель)
    
    @staticmethod
    def соединить(список, разделитель=' '):
        """Соединение списка строк в одну"""
        return разделитель.join(список)
    
    @staticmethod
    def обрезать_пробелы(строка):
        """Удаление пробелов в начале и конце строки"""
        return строка.strip()
    
    @staticmethod
    def начинается_с(строка, префикс):
        """Проверка, начинается ли строка с префикса"""
        return строка.startswith(префикс)
    
    @staticmethod
    def заканчивается_на(строка, суффикс):
        """Проверка, заканчивается ли строка суффиксом"""
        return строка.endswith(суффикс)
    
    @staticmethod
    def найти(строка, подстрока):
        """Поиск подстроки в строке (возвращает позицию или -1)"""
        return строка.find(подстрока)
    
    @staticmethod
    def содержит(строка, подстрока):
        """Проверка наличия подстроки в строке"""
        return подстрока in строка
    
    @staticmethod
    def повторить(строка, количество):
        """Повторение строки N раз"""
        return строка * количество
    
    @staticmethod
    def взять_символ(строка, позиция):
        """Получение символа по позиции"""
        if 0 <= позиция < len(строка):
            return строка[позиция]
        return None
    
    @staticmethod
    def взять_подстроку(строка, начало, конец=None):
        """Получение подстроки"""
        if конец is None:
            return строка[начало:]
        return строка[начало:конец]
    
    @staticmethod
    def вставить(строка, позиция, вставка):
        """Вставка строки в указанную позицию"""
        return строка[:позиция] + вставка + строка[позиция:]
    
    @staticmethod
    def удалить(строка, начало, конец):
        """Удаление части строки"""
        return строка[:начало] + строка[конец:]
    
    @staticmethod
    def перевернуть(строка):
        """Переворот строки задом наперед"""
        return строка[::-1]
    
    @staticmethod
    def подсчитать(строка, подстрока):
        """Подсчет количества вхождений подстроки"""
        return строка.count(подстрока)
    
    @staticmethod
    def индекс(строка, подстрока):
        """Поиск индекса первого вхождения"""
        try:
            return строка.index(подстрока)
        except ValueError:
            return -1
    
    @staticmethod
    def заполнить_слева(строка, длина, символ=' '):
        """Заполнение строки слева до указанной длины"""
        return строка.rjust(длина, символ)
    
    @staticmethod
    def заполнить_справа(строка, длина, символ=' '):
        """Заполнение строки справа до указанной длины"""
        return строка.ljust(длина, символ)
    
    @staticmethod
    def по_центру(строка, длина, символ=' '):
        """Центрирование строки"""
        return строка.center(длина, символ)
    
    @staticmethod
    def является_цифрой(строка):
        """Проверка, состоит ли строка только из цифр"""
        return строка.isdigit()
    
    @staticmethod
    def является_буквой(строка):
        """Проверка, состоит ли строка только из букв"""
        return строка.isalpha()
    
    @staticmethod
    def является_числом(строка):
        """Проверка, является ли строка числом"""
        try:
            float(строка)
            return True
        except ValueError:
            return False
    
    @staticmethod
    def в_число(строка):
        """Преобразование строки в число"""
        try:
            if '.' in строка:
                return float(строка)
            return int(строка)
        except ValueError:
            return None
    
    @staticmethod
    def в_строку(объект):
        """Преобразование объекта в строку"""
        return str(объект)
    
    @staticmethod
    def форматировать(шаблон, *аргументы):
        """Форматирование строки по шаблону"""
        return шаблон.format(*аргументы)
    
    @staticmethod
    def код_символа(символ):
        """Получение Unicode кода символа"""
        return ord(символ)
    
    @staticmethod
    def символ_из_кода(код):
        """Получение символа по Unicode коду"""
        return chr(код)


# Глобальные функции для удобного доступа
длина = Строки.длина
