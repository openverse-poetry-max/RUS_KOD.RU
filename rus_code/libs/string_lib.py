#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Библиотека работы со строками для РусКод
Расширенные функции обработки текста
"""

import re
from typing import List, Dict

class Строки:
    """Расширенная библиотека работы со строками"""
    
    @staticmethod
    def длина(s) -> int:
        """Длина строки"""
        return len(str(s))
    
    @staticmethod
    def верхний_регистр(s) -> str:
        """Преобразование к верхнему регистру"""
        return str(s).upper()
    
    @staticmethod
    def нижний_регистр(s) -> str:
        """Преобразование к нижнему регистру"""
        return str(s).lower()
    
    @staticmethod
    def заглавные_буквы(s) -> str:
        """Заглавная первая буква каждого слова"""
        return str(s).title()
    
    @staticmethod
    def первое_заглавное(s) -> str:
        """Первая буква заглавная, остальные строчные"""
        s = str(s)
        if not s:
            return s
        return s[0].upper() + s[1:].lower()
    
    @staticmethod
    def обрезать_пробелы(s) -> str:
        """Удаление пробелов с начала и конца"""
        return str(s).strip()
    
    @staticmethod
    def обрезать_слева(s) -> str:
        """Удаление пробелов слева"""
        return str(s).lstrip()
    
    @staticmethod
    def обрезать_справа(s) -> str:
        """Удаление пробелов справа"""
        return str(s).rstrip()
    
    @staticmethod
    def заменить(s, old, new, count=-1) -> str:
        """Замена подстроки"""
        if count == -1:
            return str(s).replace(old, new)
        return str(s).replace(old, new, count)
    
    @staticmethod
    def разделить_строку(s, sep=None) -> List[str]:
        """Разделение строки по разделителю"""
        if sep is None:
            return str(s).split()
        return str(s).split(sep)
    
    @staticmethod
    def соединить_строки(lst, sep='') -> str:
        """Соединение списка строк"""
        return sep.join(map(str, lst))
    
    @staticmethod
    def найти_подстроку(s, sub, start=0, end=None) -> int:
        """Поиск подстроки в строке"""
        if end is None:
            return str(s).find(sub, start)
        return str(s).find(sub, start, end)
    
    @staticmethod
    def найти_последнюю(s, sub, start=0, end=None) -> int:
        """Поиск последнего вхождения подстроки"""
        if end is None:
            return str(s).rfind(sub, start)
        return str(s).rfind(sub, start, end)
    
    @staticmethod
    def содержит(s, sub) -> bool:
        """Проверка наличия подстроки"""
        return sub in str(s)
    
    @staticmethod
    def начинается_с(s, prefix) -> bool:
        """Проверка начала строки"""
        return str(s).startswith(prefix)
    
    @staticmethod
    def заканчивается_на(s, suffix) -> bool:
        """Проверка окончания строки"""
        return str(s).endswith(suffix)
    
    @staticmethod
    def взять_символы(s, start, end=None) -> str:
        """Извлечение части строки"""
        if end is None:
            return str(s)[start:]
        return str(s)[start:end]
    
    @staticmethod
    def первый_символ(s) -> str:
        """Первый символ строки"""
        s = str(s)
        return s[0] if s else ''
    
    @staticmethod
    def последний_символ(s) -> str:
        """Последний символ строки"""
        s = str(s)
        return s[-1] if s else ''
    
    @staticmethod
    def перевернуть_строку(s) -> str:
        """Переворот строки"""
        return str(s)[::-1]
    
    @staticmethod
    def повторить_строку(s, n) -> str:
        """Повторение строки n раз"""
        return str(s) * int(n)
    
    @staticmethod
    def код_символа(s) -> int:
        """Код первого символа"""
        s = str(s)
        return ord(s[0]) if s else 0
    
    @staticmethod
    def символ_из_кода(code) -> str:
        """Символ из кода"""
        return chr(int(code))
    
    @staticmethod
    def подсчитать_вхождения(s, sub) -> int:
        """Подсчет количества вхождений подстроки"""
        return str(s).count(sub)
    
    @staticmethod
    def в_строку(x) -> str:
        """Преобразование в строку"""
        return str(x)
    
    @staticmethod
    def в_число(s) -> float:
        """Преобразование строки в число"""
        return float(str(s).replace(',', '.'))
    
    @staticmethod
    def в_целое_число(s) -> int:
        """Преобразование строки в целое число"""
        return int(float(str(s).replace(',', '.')))
    
    @staticmethod
    def форматировать_число(num, digits=2) -> str:
        """Форматирование числа с заданным количеством знаков"""
        return f"{float(num):.{int(digits)}f}"
    
    @staticmethod
    def форматировать_валюта(сумма, валюта='₽') -> str:
        """Форматирование как валюта"""
        return f"{Строки.форматировать_число(сумма, 2)} {валюта}"
    
    @staticmethod
    def форматировать_процент(значение, digits=1) -> str:
        """Форматирование как процент"""
        return f"{Строки.форматировать_число(значение, digits)}%"
    
    @staticmethod
    def дополнить_слева(s, width, fillchar=' ') -> str:
        """Дополнение строки слева до заданной ширины"""
        return str(s).rjust(width, fillchar)
    
    @staticmethod
    def дополнить_справа(s, width, fillchar=' ') -> str:
        """Дополнение строки справа до заданной ширины"""
        return str(s).ljust(width, fillchar)
    
    @staticmethod
    def дополнить_по_центру(s, width, fillchar=' ') -> str:
        """Дополнение строки по центру до заданной ширины"""
        return str(s).center(width, fillchar)
    
    @staticmethod
    def разбить_по_строкам(s) -> List[str]:
        """Разбиение текста на строки"""
        return str(s).splitlines()
    
    @staticmethod
    def объединить_строки(lst, sep='\n') -> str:
        """Объединение списка строк с разделителем"""
        return sep.join(map(str, lst))
    
    @staticmethod
    def удалить_пробелы(s) -> str:
        """Удаление всех пробелов из строки"""
        return str(s).replace(' ', '')
    
    @staticmethod
    def нормализовать_пробелы(s) -> str:
        """Нормализация множественных пробелов в один"""
        return ' '.join(str(s).split())
    
    @staticmethod
    def извлечь_числа(s) -> List[float]:
        """Извлечение всех чисел из строки"""
        числа = re.findall(r'-?\d+\.?\d*', str(s))
        return [float(x.replace(',', '.')) for x in числа if x]
    
    @staticmethod
    def извлечь_слова(s) -> List[str]:
        """Извлечение всех слов из строки"""
        return re.findall(r'[а-яА-ЯёЁa-zA-Z]+', str(s))
    
    @staticmethod
    def удалить_знаки_препинания(s) -> str:
        """Удаление знаков препинания"""
        return re.sub(r'[^\w\s]', '', str(s))
    
    @staticmethod
    def транслитерация(s) -> str:
        """Транслитерация кириллицы в латиницу"""
        карта = {
            'а': 'a', 'б': 'b', 'в': 'v', 'г': 'g', 'д': 'd',
            'е': 'e', 'ё': 'yo', 'ж': 'zh', 'з': 'z', 'и': 'i',
            'й': 'y', 'к': 'k', 'л': 'l', 'м': 'm', 'н': 'n',
            'о': 'o', 'п': 'p', 'р': 'r', 'с': 's', 'т': 't',
            'у': 'u', 'ф': 'f', 'х': 'kh', 'ц': 'ts', 'ч': 'ch',
            'ш': 'sh', 'щ': 'sch', 'ъ': '', 'ы': 'y', 'ь': '',
            'э': 'e', 'ю': 'yu', 'я': 'ya',
            'А': 'A', 'Б': 'B', 'В': 'V', 'Г': 'G', 'Д': 'D',
            'Е': 'E', 'Ё': 'Yo', 'Ж': 'Zh', 'З': 'Z', 'И': 'I',
            'Й': 'Y', 'К': 'K', 'Л': 'L', 'М': 'M', 'Н': 'N',
            'О': 'O', 'П': 'P', 'Р': 'R', 'С': 'S', 'Т': 'T',
            'У': 'U', 'Ф': 'F', 'Х': 'Kh', 'Ц': 'Ts', 'Ч': 'Ch',
            'Ш': 'Sh', 'Щ': 'Sch', 'Ъ': '', 'Ы': 'Y', 'Ь': '',
            'Э': 'E', 'Ю': 'Yu', 'Я': 'Ya'
        }
        результат = ''
        for char in str(s):
            результат += карта.get(char, char)
        return результат
    
    @staticmethod
    def проверить_email(email) -> bool:
        """Проверка корректности email"""
        pattern = r'^[\w\.-]+@[\w\.-]+\.\w+$'
        return bool(re.match(pattern, str(email)))
    
    @staticmethod
    def проверить_телефон(телефон, формат='ru') -> bool:
        """Проверка номера телефона"""
        if формат == 'ru':
            pattern = r'^\+?7[\s\-]?\(?\d{3}\)?[\s\-]?\d{3}[\s\-]?\d{2}[\s\-]?\d{2}$'
        elif формат == 'us':
            pattern = r'^\+?1[\s\-]?\(?\d{3}\)?[\s\-]?\d{3}[\s\-]?\d{4}$'
        else:
            pattern = r'^\+?\d{10,15}$'
        return bool(re.match(pattern, str(телефон).replace(' ', '').replace('-', '')))
    
    @staticmethod
    def проверить_url(url) -> bool:
        """Проверка URL адреса"""
        pattern = r'^https?://[\w\.-]+\.[\w\.-]+(/[\w\./\-]*)?$'
        return bool(re.match(pattern, str(url)))
    
    @staticmethod
    def скрыть_email(email) -> str:
        """Скрытие email для отображения"""
        email = str(email)
        if '@' not in email:
            return email
        имя, домен = email.split('@', 1)
        if len(имя) <= 2:
            скрыто = имя[0] + '*'
        else:
            скрыто = имя[0] + '*' * (len(имя) - 2) + имя[-1]
        return f"{скрыто}@{домен}"
    
    @staticmethod
    def скрыть_телефон(телефон) -> str:
        """Скрытие телефона для отображения"""
        телефон = str(телефон)
        цифры = re.sub(r'\D', '', телефон)
        if len(цифры) < 4:
            return телефон
        return телефон[:-4] + '****'
    
    @staticmethod
    def генератор_паролей(длина=12, использовать_заглавные=True, 
                          использовать_цифры=True, использовать_спец=True) -> str:
        """Генерация случайного пароля"""
        import random
        
        символы = 'абвгдеёжзийклмнопрстуфхцчшщъыьэюя'
        if использовать_заглавные:
            символы += 'АБВГДЕЁЖЗИЙКЛМНОПРСТУФХЦЧШЩЪЫЬЭЮЯ'
        if использовать_цифры:
            символы += '0123456789'
        if использовать_спец:
            символы += '!@#$%^&*()_+-=[]{}|;:,.<>?'
        
        пароль = ''.join(random.choice(символы) for _ in range(длина))
        return пароль
    
    @staticmethod
    def хеш_строки(s, mod=10**9+7) -> int:
        """Простой хеш строки"""
        хеш = 0
        for char in str(s):
            хеш = (хеш * 31 + ord(char)) % mod
        return хеш
    
    @staticmethod
    def расстояние_левенштейна(s1, s2) -> int:
        """Расстояние Левенштейна между строками"""
        s1, s2 = str(s1), str(s2)
        m, n = len(s1), len(s2)
        
        # Создаем матрицу
        dp = [[0] * (n + 1) for _ in range(m + 1)]
        
        # Инициализация первой строки и столбца
        for i in range(m + 1):
            dp[i][0] = i
        for j in range(n + 1):
            dp[0][j] = j
        
        # Заполнение матрицы
        for i in range(1, m + 1):
            for j in range(1, n + 1):
                if s1[i-1] == s2[j-1]:
                    dp[i][j] = dp[i-1][j-1]
                else:
                    dp[i][j] = 1 + min(dp[i-1][j],      # удаление
                                       dp[i][j-1],      # вставка
                                       dp[i-1][j-1])    # замена
        
        return dp[m][n]
    
    @staticmethod
    def похожесть_строк(s1, s2) -> float:
        """Коэффициент похожести строк (0-1)"""
        s1, s2 = str(s1), str(s2)
        if not s1 and not s2:
            return 1.0
        max_len = max(len(s1), len(s2))
        if max_len == 0:
            return 1.0
        расстояние = Строки.расстояние_левенштейна(s1, s2)
        return 1 - (расстояние / max_len)


