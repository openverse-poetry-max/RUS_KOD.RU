заменить = Строки.заменить
разделить = Строки.разделить
соединить = Строки.соединить
обрезать_пробелы = Строки.обрезать_пробелы
содержит = Строки.содержит
повторить = Строки.повторить
перевернуть = Строки.перевернуть
в_число = Строки.в_число
в_строку = Строки.в_строку
