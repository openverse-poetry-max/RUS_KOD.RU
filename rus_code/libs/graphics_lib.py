"""
Библиотека графических функций для РусКод
Все функции на русском языке без английских букв
Поддержка простой векторной графики
"""

class Графика:
    """Библиотека графических функций"""
    
    @staticmethod
    def создать_холст(ширина=800, высота=600):
        """Создание графического холста"""
        return {
            'тип': 'холст',
            'ширина': ширина,
            'высота': высота,
            'объекты': []
        }
    
    @staticmethod
    def нарисовать_круг(х, у, радиус, цвет='черный'):
        """Рисование круга"""
        return {
            'тип': 'круг',
            'х': х,
            'у': у,
            'радиус': радиус,
            'цвет': цвет
        }
    
    @staticmethod
    def нарисовать_квадрат(х, у, размер, цвет='черный'):
        """Рисование квадрата"""
        return {
            'тип': 'квадрат',
            'х': х,
            'у': у,
            'размер': размер,
            'цвет': цвет
        }
    
    @staticmethod
    def нарисовать_прямоугольник(х, у, ширина, высота, цвет='черный'):
        """Рисование прямоугольника"""
        return {
            'тип': 'прямоугольник',
            'х': х,
            'у': у,
            'ширина': ширина,
            'высота': высота,
            'цвет': цвет
        }
    
    @staticmethod
    def нарисовать_треугольник(х1, у1, х2, у2, х3, у3, цвет='черный'):
        """Рисование треугольника"""
        return {
            'тип': 'треугольник',
            'точки': [(х1, у1), (х2, у2), (х3, у3)],
            'цвет': цвет
        }
    
    @staticmethod
    def нарисовать_линию(х1, у1, х2, у2, цвет='черный', толщина=1):
        """Рисование линии"""
        return {
            'тип': 'линия',
            'начало': (х1, у1),
            'конец': (х2, у2),
            'цвет': цвет,
            'толщина': толщина
        }
    
    @staticmethod
    def нарисовать_точку(х, у, цвет='черный', размер=1):
        """Рисование точки"""
        return {
            'тип': 'точка',
            'х': х,
            'у': у,
            'цвет': цвет,
            'размер': размер
        }
    
    @staticmethod
    def нарисовать_текст(х, у, текст, шрифт='Arial', размер=12, цвет='черный'):
        """Рисование текста"""
        return {
            'тип': 'текст',
            'х': х,
            'у': у,
            'текст': текст,
            'шрифт': шрифт,
            'размер': размер,
            'цвет': цвет
        }
    
    @staticmethod
    def нарисовать_эллипс(х, у, радиус_х, радиус_у, цвет='черный'):
        """Рисование эллипса"""
        return {
            'тип': 'эллипс',
            'центр': (х, у),
            'радиус_х': радиус_х,
            'радиус_у': радиус_у,
            'цвет': цвет
        }
    
    @staticmethod
    def нарисовать_многоугольник(точки, цвет='черный'):
        """Рисование многоугольника"""
        return {
            'тип': 'многоугольник',
            'точки': точки,
            'цвет': цвет
        }
    
    @staticmethod
    def нарисовать_звезду(х, у, внешний_радиус, внутренний_радиус, лучей=5, цвет='черный'):
        """Рисование звезды"""
        import math
        точки = []
        for i in range(лучей * 2):
            угол = math.pi / 2 + i * math.pi / лучей
            радиус = внешний_радиус if i % 2 == 0 else внутренний_радиус
            точки.append((
                х + радиус * math.cos(угол),
                у + радиус * math.sin(угол)
            ))
        return {
            'тип': 'звезда',
            'центр': (х, у),
            'внешний_радиус': внешний_радиус,
            'внутренний_радиус': внутренний_радиус,
            'лучей': лучей,
            'точки': точки,
            'цвет': цвет
        }
    
    @staticmethod
    def добавить_на_холст(холст, объект):
        """Добавление объекта на холст"""
        холст['объекты'].append(объект)
        return холст
    
    @staticmethod
    def очистить_холст(холст):
        """Очистка холста"""
        холст['объекты'] = []
        return холст
    
    @staticmethod
    def сохранить_холст(холст, имя_файла):
        """Сохранение холста в файл (имитация)"""
        return f"Холст сохранен в файл: {имя_файла}"
    
    @staticmethod
    def показать_холст(холст):
        """Отображение холста (имитация)"""
        описание = f"Холст {холст['ширина']}x{холст['высота']} с {len(холст['объекты'])} объектами:\n"
        for объект in холст['объекты']:
            описание += f"  - {объект['тип']}\n"
        return описание
    
    @staticmethod
    def установить_цвет_фона(холст, цвет):
        """Установка цвета фона"""
        холст['фон'] = цвет
        return холст
    
    @staticmethod
    def переместить(объект, дельта_х, дельта_у):
        """Перемещение объекта"""
        if 'х' in объект:
            объект['х'] += дельта_х
        if 'у' in объект:
            объект['у'] += дельта_у
        if 'начало' in объект:
            объект['начало'] = (объект['начало'][0] + дельта_х, объект['начало'][1] + дельта_у)
        if 'конец' in объект:
            объект['конец'] = (объект['конец'][0] + дельта_х, объект['конец'][1] + дельта_у)
        if 'центр' in объект:
            объект['центр'] = (объект['центр'][0] + дельта_х, объект['центр'][1] + дельта_у)
        if 'точки' in объект and объект['тип'] != 'линия':
            объект['точки'] = [(х + дельта_х, у + дельта_у) for х, у in объект['точки']]
        return объект
    
    @staticmethod
    def масштабировать(объект, коэффициент):
        """Масштабирование объекта"""
        if 'радиус' in объект:
            объект['радиус'] *= коэффициент
        if 'размер' in объект:
            объект['размер'] *= коэффициент
        if 'ширина' in объект:
            объект['ширина'] *= коэффициент
        if 'высота' in объект:
            объект['высота'] *= коэффициент
        return объект


