class Графика:
    """Библиотека графических функций"""
    
    @staticmethod
    def создать_холст(ширина=800, высота=600) -> Холст:
        """Создать новый холст"""
        return Холст(ширина, высота)
    
    @staticmethod
    def нарисовать_точку(холст: Холст, x: int, y: int, цвет: str = '#000000'):
        """Нарисовать точку"""
        холст.установить_пиксель(x, y, цвет)
        холст.фигуры.append({'тип': 'точка', 'x': x, 'y': y, 'цвет': цвет})
    
    @staticmethod
    def нарисовать_линию(холст: Холст, x1: int, y1: int, x2: int, y2: int, 
                         цвет: str = '#000000', толщина: int = 1):
        """Нарисовать линию алгоритмом Брезенхэма"""
        dx = abs(x2 - x1)
        dy = abs(y2 - y1)
        sx = 1 if x1 < x2 else -1
        sy = 1 if y1 < y2 else -1
        err = (dx if dx > dy else -dy) / 2
        
        while True:
            for i in range(-толщина//2, толщина//2 + 1):
                for j in range(-толщина//2, толщина//2 + 1):
                    холст.установить_пиксель(x1 + i, y1 + j, цвет)
            
            if x1 == x2 and y1 == y2:
                break
            e2 = err
            if e2 > -dx:
                err -= dy
                x1 += sx
            if e2 < dy:
                err += dx
                y1 += sy
        
        холст.фигуры.append({
            'тип': 'линия', 'x1': x1, 'y1': y1, 'x2': x2, 'y2': y2, 
            'цвет': цвет, 'толщина': толщина
        })
    
    @staticmethod
    def нарисовать_круг(холст: Холст, cx: int, cy: int, радиус: int, 
                        цвет: str = '#000000', заливка: bool = False):
        """Нарисовать круг"""
        x = радиус
        y = 0
        err = 0
        
        while x >= y:
            if заливка:
                # Заливка круга
                for px in range(cx - x, cx + x + 1):
                    py = cy + y
                    if 0 <= py < холст.высота:
                        холст.установить_пиксель(px, py, цвет)
                    py = cy - y
                    if 0 <= py < холст.высота:
                        холст.установить_пиксель(px, py, цвет)
                for px in range(cx - y, cx + y + 1):
                    py = cy + x
                    if 0 <= py < холст.высота:
                        холст.установить_пиксель(px, py, цвет)
                    py = cy - x
                    if 0 <= py < холст.высота:
                        холст.установить_пиксель(px, py, цвет)
            else:
                # Контур круга
                Графика.нарисовать_точку(холст, cx + x, cy + y, цвет)
                Графика.нарисовать_точку(холст, cx + y, cy + x, цвет)
                Графика.нарисовать_точку(холст, cx - y, cy + x, цвет)
                Графика.нарисовать_точку(холст, cx - x, cy + y, цвет)
                Графика.нарисовать_точку(холст, cx - x, cy - y, цвет)
                Графика.нарисовать_точку(холст, cx - y, cy - x, цвет)
                Графика.нарисовать_точку(холст, cx + y, cy - x, цвет)
                Графика.нарисовать_точку(холст, cx + x, cy - y, цвет)
            
            y += 1
            err += 1 + 2 * y
            if 2 * (err - x) + 1 > 0:
                x -= 1
                err += 1 - 2 * x
        
        холст.фигуры.append({
            'тип': 'круг', 'cx': cx, 'cy': cy, 'радиус': радиус, 
            'цвет': цвет, 'заливка': заливка
        })
    
    @staticmethod
    def нарисовать_прямоугольник(холст: Холст, x: int, y: int, ширина: int, высота: int,
                                   цвет: str = '#000000', заливка: bool = False):
        """Нарисовать прямоугольник"""
        if заливка:
            for py in range(y, y + высота):
                for px in range(x, x + ширина):
                    холст.установить_пиксель(px, py, цвет)
        else:
            # Верхняя линия
            Графика.нарисовать_линию(холст, x, y, x + ширина, y, цвет)
            # Нижняя линия
            Графика.нарисовать_линию(холст, x, y + высота, x + ширина, y + высота, цвет)
            # Левая линия
            Графика.нарисовать_линию(холст, x, y, x, y + высота, цвет)
            # Правая линия
            Графика.нарисовать_линию(холст, x + ширина, y, x + ширина, y + высота, цвет)
        
        холст.фигуры.append({
            'тип': 'прямоугольник', 'x': x, 'y': y, 'ширина': ширина, 'высота': высота,
            'цвет': цвет, 'заливка': заливка
        })
    
    @staticmethod
    def нарисовать_квадрат(холст: Холст, x: int, y: int, размер: int,
                           цвет: str = '#000000', заливка: bool = False):
        """Нарисовать квадрат"""
        return Графика.нарисовать_прямоугольник(холст, x, y, размер, размер, цвет, заливка)
    
    @staticmethod
    def нарисовать_треугольник(холст: Холст, x1: int, y1: int, x2: int, y2: int, 
                               x3: int, y3: int, цвет: str = '#000000', заливка: bool = False):
        """Нарисовать треугольник"""
        if заливка:
            # Простая реализация через сканирование строк
            точки = [(x1, y1), (x2, y2), (x3, y3)]
            min_y = min(p[1] for p in точки)
            max_y = max(p[1] for p in точки)
            
            for y in range(min_y, max_y + 1):
                пересечения = []
                for i in range(3):
                    j = (i + 1) % 3
                    if (точки[i][1] <= y < точки[j][1]) or (точки[j][1] <= y < точки[i][1]):
                        if точки[j][1] != точки[i][1]:
                            x = точки[i][0] + (y - точки[i][1]) * (точки[j][0] - точки[i][0]) / (точки[j][1] - точки[i][1])
                            пересечения.append(int(x))
                
                пересечения.sort()
                for i in range(0, len(пересечения) - 1, 2):
                    for x in range(пересечения[i], пересечения[i+1] + 1):
                        холст.установить_пиксель(x, y, цвет)
        else:
            Графика.нарисовать_линия(холст, x1, y1, x2, y2, цвет)
            Графика.нарисовать_линия(холст, x2, y2, x3, y3, цвет)
            Графика.нарисовать_линия(холст, x3, y3, x1, y1, цвет)
        
        холст.фигуры.append({
            'тип': 'треугольник', 'точки': [(x1, y1), (x2, y2), (x3, y3)],
            'цвет': цвет, 'заливка': заливка
        })
    
    @staticmethod
    def нарисовать_эллипс(холст: Холст, cx: int, cy: int, rx: int, ry: int,
                          цвет: str = '#000000', заливка: bool = False):
        """Нарисовать эллипс"""
        dx = 0
        dy = ry
        a2 = rx * rx
        b2 = ry * ry
        err = b2 - (rx * rx * ry)
        
        while dx <= rx:
            if заливка:
                for px in range(cx - dx, cx + dx + 1):
                    холст.установить_пиксель(px, cy + dy, цвет)
                    холст.установить_пиксель(px, cy - dy, цвет)
                for px in range(cx - dx, cx + dx + 1):
                    холст.установить_пиксель(px, cy + err // a2, цвет)
                    холст.установить_пиксель(px, cy - err // a2, цвет)
            else:
                Графика.нарисовать_точку(холст, cx + dx, cy + dy, цвет)
                Графика.нарисовать_точку(холст, cx - dx, cy + dy, цвет)
                Графика.нарисовать_точку(холст, cx + dx, cy - dy, цвет)
                Графика.нарисовать_точку(холст, cx - dx, cy - dy, цвет)
                Графика.нарисовать_точку(холст, cx + err // b2, cy + dy, цвет)
                Графика.нарисовать_точку(холст, cx - err // b2, cy + dy, цвет)
                Графика.нарисовать_точку(холст, cx + err // b2, cy - dy, цвет)
                Графика.нарисовать_точку(холст, cx - err // b2, cy - dy, цвет)
            
            err += b2 * (2 * dx + 1)
            dx += 1
            err -= a2 * (2 * dy - 1)
            if err > 0:
                dy -= 1
        
        холст.фигуры.append({
            'тип': 'эллипс', 'cx': cx, 'cy': cy, 'rx': rx, 'ry': ry,
            'цвет': цвет, 'заливка': заливка
        })
    
    @staticmethod
    def нарисовать_многоугольник(холст: Холст, точки: List[Tuple[int, int]],
                                  цвет: str = '#000000', заливка: bool = False):
        """Нарисовать многоугольник по списку точек"""
        if len(точки) < 3:
            return
        
        if заливка:
            min_y = min(p[1] for p in точки)
            max_y = max(p[1] for p in точки)
            
            for y in range(min_y, max_y + 1):
                пересечения = []
                n = len(точки)
                for i in range(n):
                    j = (i + 1) % n
                    if (точки[i][1] <= y < точки[j][1]) or (точки[j][1] <= y < точки[i][1]):
                        if точки[j][1] != точки[i][1]:
                            x = точки[i][0] + (y - точки[i][1]) * (точки[j][0] - точки[i][0]) / (точки[j][1] - точки[i][1])
                            пересечения.append(int(x))
                
                пересечения.sort()
                for i in range(0, len(пересечения) - 1, 2):
                    for x in range(пересечения[i], пересечения[i+1] + 1):
                        холст.установить_пиксель(x, y, цвет)
        else:
            n = len(точки)
            for i in range(n):
                j = (i + 1) % n
                Графика.нарисовать_линия(холст, точки[i][0], точки[i][1], 
                                         точки[j][0], точки[j][1], цвет)
        
        холст.фигуры.append({
            'тип': 'многоугольник', 'точки': точки, 'цвет': цвет, 'заливка': заливка
        })
    
    @staticmethod
    def нарисовать_звезду(холст: Холст, cx: int, cy: int, внешний_радиус: int,
                          внутренний_радиус: int, лучей: int = 5,
                          цвет: str = '#FFD700', заливка: bool = True):
        """Нарисовать звезду"""
        точки = []
        угол = -math.pi / 2
        
        for i in range(лучей * 2):
            радиус = внешний_радиус if i % 2 == 0 else внутренний_радиус
            x = cx + int(радиус * math.cos(угол))
            y = cy + int(радиус * math.sin(угол))
            точки.append((x, y))
            угол += math.pi / лучей
        
        return Графика.нарисовать_многоугольник(холст, точки, цвет, заливка)
    
    @staticmethod
    def залить_область(холст: Холст, x: int, y: int, цвет: str = '#000000'):
        """Заливка области (алгоритм flood fill)"""
        исходный_цвет = холст.получить_пиксель(x, y)
        if исходный_цвет == цвет:
            return
        
        стек = [(x, y)]
        посещенные = set()
        
        while стек:
            px, py = стек.pop()
            if (px, py) in посещенные:
                continue
            if not (0 <= px < холст.ширина and 0 <= py < холст.высота):
                continue
            
            текущий = холст.получить_пиксель(px, py)
            if текущий is not None and текущий != исходный_цвет:
                continue
            
            холст.установить_пиксель(px, py, цвет)
            посещенные.add((px, py))
            
            стек.extend([(px+1, py), (px-1, py), (px, py+1), (px, py-1)])
    
    @staticmethod
    def повернуть_точку(x: int, y: int, угол: float, cx: int = 0, cy: int = 0) -> Tuple[int, int]:
        """Повернуть точку вокруг центра"""
        рад = math.radians(угол)
        cos_a = math.cos(рад)
        sin_a = math.sin(рад)
        
        # Сдвиг к центру вращения
        x -= cx
        y -= cy
        
        # Поворот
        новый_x = x * cos_a - y * sin_a
        новый_y = x * sin_a + y * cos_a
        
        # Обратный сдвиг
        return (int(новый_x + cx), int(новый_y + cy))
    
    @staticmethod
    def масштабировать_точку(x: int, y: int, масштаб: float, cx: int = 0, cy: int = 0) -> Tuple[int, int]:
        """Масштабировать точку относительно центра"""
        x -= cx
        y -= cy
        
        новый_x = x * масштаб
        новый_y = y * масштаб
        
        return (int(новый_x + cx), int(новый_y + cy))
    
    @staticmethod
    def смешать_цвета(цвет1: str, цвет2: str, коэффициент: float = 0.5) -> str:
        """Смешать два цвета"""
        r1, g1, b1 = int(цвет1[1:3], 16), int(цвет1[3:5], 16), int(цвет1[5:7], 16)
        r2, g2, b2 = int(цвет2[1:3], 16), int(цвет2[3:5], 16), int(цвет2[5:7], 16)
        
        r = int(r1 * (1 - коэффициент) + r2 * коэффициент)
        g = int(g1 * (1 - коэффициент) + g2 * коэффициент)
        b = int(b1 * (1 - коэффициент) + b2 * коэффициент)
        
        return f"#{r:02X}{g:02X}{b:02X}"
    
    @staticmethod
    def инвертировать_цвет(цвет: str) -> str:
        """Инвертировать цвет"""
        r = 255 - int(цвет[1:3], 16)
        g = 255 - int(цвет[3:5], 16)
        b = 255 - int(цвет[5:7], 16)
        return f"#{r:02X}{g:02X}{b:02X}"
    
    @staticmethod
    def осветлить_цвет(цвет: str, процент: float = 0.1) -> str:
        """Осветлить цвет"""
        r = int(int(цвет[1:3], 16) * (1 + процент))
        g = int(int(цвет[3:5], 16) * (1 + процент))
        b = int(int(цвет[5:7], 16) * (1 + процент))
        r, g, b = min(r, 255), min(g, 255), min(b, 255)
        return f"#{r:02X}{g:02X}{b:02X}"
    
    @staticmethod
    def затемнить_цвет(цвет: str, процент: float = 0.1) -> str:
        """Затемнить цвет"""
        r = int(int(цвет[1:3], 16) * (1 - процент))
        g = int(int(цвет[3:5], 16) * (1 - процент))
        b = int(int(цвет[5:7], 16) * (1 - процент))
        r, g, b = max(r, 0), max(g, 0), max(b, 0)
        return f"#{r:02X}{g:02X}{b:02X}"


