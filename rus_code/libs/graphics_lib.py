import math
from typing import List, Tuple, Optional

class Холст:
    """Класс графического холста"""
    
    def __init__(self, ширина=800, высота=600):
        self.ширина = ширина
        self.высота = высота
        self.пиксели = {}  # {(x, y): цвет}
        self.фигуры = []  # список нарисованных фигур
    
    def очистить(self):
        """Очистить холст"""
        self.пиксели = {}
        self.фигуры = []
    
    def установить_пиксель(self, x: int, y: int, цвет: str = '#000000'):
        """Установить цвет пикселя"""
        if 0 <= x < self.ширина and 0 <= y < self.высота:
            self.пиксели[(x, y)] = цвет
    
    def получить_пиксель(self, x: int, y: int) -> Optional[str]:
        """Получить цвет пикселя"""
        return self.пиксели.get((x, y), None)
    
