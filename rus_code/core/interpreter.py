"""
РусКод - Универсальный язык программирования на русском языке
Версия 1.0

Особенности:
- Полностью русский синтаксис
- Понимание естественной речи
- Простота для детей 7-8 лет
- Мощные возможности для взрослых разработчиков
- Богатая библиотека готовых функций
"""

import re
import math
import random
import datetime
from typing import Any, Dict, List, Optional, Callable

class РусКодИнтерпретатор:
    """Основной интерпретатор языка РусКод"""
    
    def __init__(self):
        self.переменные = {}
        self.библиотеки = {}
        self.функции = {}
        self.результат = None
        
        # Регистрация встроенных функций
        self._зарегистрировать_встроенные_функции()
    
    def _зарегистрировать_встроенные_функции(self):
        """Регистрация встроенных функций языка"""
        
        # Математические функции
        self.функции['плюс'] = lambda *args: sum(args) if all(isinstance(x, (int, float)) for x in args) else ' '.join(map(str, args))
        self.функции['минус'] = lambda x, y: x - y
        self.функции['умножить'] = lambda x, y: x * y
        self.функции['разделить'] = lambda x, y: x / y if y != 0 else 0
        self.функции['степень'] = lambda x, y: x ** y
        self.функции['корень'] = lambda x: math.sqrt(x)
        self.функции['модуль'] = lambda x: abs(x)
        self.функции['округлить'] = lambda x, n=0: round(x, int(n))
        
        # Строковые функции
        self.функции['длина'] = lambda x: len(str(x))
        self.функции['верхний_регистр'] = lambda x: str(x).upper()
        self.функции['нижний_регистр'] = lambda x: str(x).lower()
        self.функции['заменить'] = lambda s, old, new: str(s).replace(old, new)
        self.функции['разделить_строку'] = lambda s, sep=' ': str(s).split(sep)
        
        # Функции ввода-вывода
        self.функции['написать'] = lambda *x: print(' '.join(map(str, x)), end='')
        self.функции['написать_строку'] = lambda *x: print(' '.join(map(str, x)))
        self.функции['спросить'] = lambda prompt='': input(prompt)
        
        # Случайные числа
        self.функции['случайное_число'] = lambda min_val=0, max_val=100: random.randint(min_val, max_val)
        
        # Списочные функции
        self.функции['создать_список'] = lambda *args: list(args)
        self.функции['добавить_в_список'] = lambda lst, item: lst.append(item) or lst
        self.функции['длина_списка'] = lambda lst: len(lst)
        self.функции['взять_из_списка'] = lambda lst, idx: lst[idx] if 0 <= idx < len(lst) else None
        
        # Логические функции
        self.функции['и'] = lambda x, y: x and y
        self.функции['или'] = lambda x, y: x or y
        self.функции['не'] = lambda x: not x
        self.функции['равно'] = lambda x, y: x == y
        self.функции['не_равно'] = lambda x, y: x != y
        self.функции['больше'] = lambda x, y: x > y
        self.функции['меньше'] = lambda x, y: x < y
        self.функции['больше_или_равно'] = lambda x, y: x >= y
        self.функции['меньше_или_равно'] = lambda x, y: x <= y
        
        # Функции работы с датой и временем
        сейчас = datetime.datetime.now()
        self.функции['текущая_дата'] = lambda: сейчас.strftime('%Y-%m-%d')
        self.функции['текущее_время'] = lambda: сейчас.strftime('%H:%M:%S')
        
        # Графические функции (упрощенные)
        self.функции['нарисовать_круг'] = lambda x=100, y=100, r=50: f"Круг в точке ({x},{y}) радиусом {r}"
        self.функции['нарисовать_квадрат'] = lambda x=100, y=100, size=50: f"Квадрат в точке ({x},{y}) размером {size}"
        self.функции['нарисовать_линию'] = lambda x1=0, y1=0, x2=100, y2=100: f"Линия от ({x1},{y1}) до ({x2},{y2})"
        
        # Звуковые функции (упрощенные)
        self.функции['воспроизвести_звук'] = lambda freq=440, duration=1: f"Звук частотой {freq}Гц длительностью {duration}с"
    
    def выполнить(self, код: str) -> Any:
        """Выполнение кода на языке РусКод"""
        строки = код.strip().split('\n')
        
        for строка in строки:
            строка = строка.strip()
            if not строка or строка.startswith('#'):
                continue
            
            результат = self._обработать_строку(строка)
            if результат is not None:
                self.результат = результат
        
        return self.результат
    
    def _обработать_строку(self, строка: str) -> Any:
        """Обработка одной строки кода"""
        
        # Обработка присваивания: "переменная равна значение" или "пусть переменная будет значение"
        паттерн_присваивания = r'(?:пусть\s+)?(\w+)\s+(?:будет|равна|равно|=)\s+(.+)'
        совпадение = re.match(паттерн_присваивания, строка, re.IGNORECASE)
        if совпадение:
            имя_переменной = совпадение.group(1)
            значение = self._вычислить_выражение(совпадение.group(2))
            self.переменные[имя_переменной] = значение
            return значение
        
        # Обработка вывода: "написать ..." или "показать ..." или "написать_строку ..."
        паттерн_вывода = r'написать_строку\s*\((.+)\)'
        совпадение = re.match(паттерн_вывода, строка, re.IGNORECASE)
        if совпадение:
            значение = self._вычислить_выражение(совпадение.group(1))
            print(значение)
            return значение
        
        паттерн_вывода2 = r'(?:написать|показать|отобразить)\s+(.+)'
        совпадение = re.match(паттерн_вывода2, строка, re.IGNORECASE)
        if совпадение:
            значение = self._вычислить_выражение(совпадение.group(1))
            print(значение)
            return значение
        
        # Обработка условия: "если условие то действие"
        паттерн_если = r'если\s+(.+)\s+то\s+(.+)'
        совпадение = re.match(паттерн_если, строка, re.IGNORECASE)
        if совпадение:
            условие = self._вычислить_выражение(совпадение.group(1))
            if условие:
                return self._вычислить_выражение(совпадение.group(2))
            return None
        
        # Обработка цикла: "повторить N раз действие"
        паттерн_цикл = r'повторить\s+(\d+)\s+раз(?:а)?\s+(.+)'
        совпадение = re.match(паттерн_цикл, строка, re.IGNORECASE)
        if совпадение:
            количество = int(совпадение.group(1))
            действие = совпадение.group(2)
            результат = None
            for i in range(количество):
                результат = self._вычислить_выражение(действие)
            return результат
        
        # Обращение к функции
        return self._вычислить_выражение(строка)
    
    def _вычислить_выражение(self, выражение: str) -> Any:
        """Вычисление выражения"""
        выражение = выражение.strip()
        
        # Проверка на число
        try:
            if '.' in выражение:
                return float(выражение)
            return int(выражение)
        except ValueError:
            pass
        
        # Проверка на строку (в кавычках)
        if (выражение.startswith('"') and выражение.endswith('"')) or \
           (выражение.startswith("'") and выражение.endswith("'")):
            return выражение[1:-1]
        
        # Проверка на переменную
        if выражение in self.переменные:
            return self.переменные[выражение]
        
        # Проверка на логические значения
        if выражение.lower() in ['истина', 'правда', 'да']:
            return True
        if выражение.lower() in ['ложь', 'неправда', 'нет']:
            return False
        
        # Обработка вызова функции
        return self._обработать_вызов_функции(выражение)
    
    def _обработать_вызов_функции(self, выражение: str) -> Any:
        """Обработка вызова функции"""
        
        # Паттерн для вызова функции: функция(аргумент1, аргумент2, ...)
        # Улучшенный паттерн с захватом всех вложенных скобок
        паттерн_функции = r'^(\w+)\s*\((.+)\)$'
        совпадение = re.match(паттерн_функции, выражение.strip())
        
        if совпадение:
            имя_функции = совпадение.group(1).lower()
            аргументы_строка = совпадение.group(2)
            
            # Разбор аргументов - учитываем вложенные вызовы функций
            аргументы = self._разобрать_аргументы(аргументы_строка)
            
            # Вызов функции
            if имя_функции in self.функции:
                try:
                    return self.функции[имя_функции](*аргументы)
                except Exception as e:
                    return f"Ошибка при вызове функции {имя_функции}: {e}"
            else:
                return f"Неизвестная функция: {имя_функции}"
        
        # Если не функция, пробуем как математическое выражение
        return self._вычислить_математическое_выражение(выражение)
    
    def _разобрать_аргументы(self, аргументы_строка: str) -> list:
        """Разбор аргументов с учетом вложенных функций и строк"""
        аргументы = []
        текущий = ""
        глубина = 0
        в_строке = False
        кавычка = None
        
        for символ in аргументы_строка:
            if символ in '"\'':
                if not в_строке:
                    в_строке = True
                    кавычка = символ
                elif символ == кавычка:
                    в_строке = False
                текущий += символ
            elif символ == '(' and not в_строке:
                глубина += 1
                текущий += символ
            elif символ == ')' and not в_строке:
                глубина -= 1
                текущий += символ
            elif символ == ',' and глубина == 0 and not в_строке:
                if текущий.strip():
                    аргументы.append(self._вычислить_выражение(текущий.strip()))
                текущий = ""
            else:
                текущий += символ
        
        if текущий.strip():
            аргументы.append(self._вычислить_выражение(текущий.strip()))
        
        return аргументы
    
    def _вычислить_математическое_выражение(self, выражение: str) -> Any:
        """Вычисление математического выражения с русскими операторами"""
        
        # Замена русских операторов на Python
        выражение = выражение.lower()
        выражение = выражение.replace(' плюс ', ' + ')
        выражение = выражение.replace(' минус ', ' - ')
        выражение = выражение.replace(' умножить ', ' * ')
        выражение = выражение.replace(' разделить ', ' / ')
        выражение = выражение.replace(' степень ', ' ** ')
        
        # Подстановка значений переменных
        for имя, значение in self.переменные.items():
            выражение = re.sub(r'\b' + имя + r'\b', str(значение), выражение)
        
        try:
            # Безопасное вычисление
            return eval(выражение, {"__builtins__": {}}, {})
        except:
            return выражение


def запустить_рускод(код: str):
    """Запуск кода на языке РусКод"""
    интерпретатор = РусКодИнтерпретатор()
    return интерпретатор.выполнить(код)


